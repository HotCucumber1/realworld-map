// Cloud credentials are read from local.properties (git-ignored) or environment variables.
// Without them the app works fully offline and the sync screen explains how to configure the backend.
val localProps = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun secret(key: String, env: String): String =
    (localProps.getProperty(key) ?: System.getenv(env) ?: "").trim()

// Release signing (optional): keystore.properties in the project root, git-ignored.
//   storeFile=/absolute/path/release.jks
//   storePassword=…
//   keyAlias=…
//   keyPassword=…
// Without it assembleRelease produces an unsigned APK.
val keystoreProps = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun String.asBuildConfigString(): String = "\"" + replace("\\", "\\\\").replace("\"", "\\\"") + "\""

